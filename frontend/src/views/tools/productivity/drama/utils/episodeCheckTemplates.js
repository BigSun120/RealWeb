1. **最小化修改**：只修改有明确问题的部分，其他内容保持原样
2. **保持原有风格**：修改时要符合原作的语言风格和叙事节奏
3. **尊重创作意图**：不要因个人偏好而改变作者的创作方向
4. **聚焦核心问题**：围绕问题描述进行针对性修复，不做无关优化

